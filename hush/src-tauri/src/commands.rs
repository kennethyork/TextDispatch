#[tauri::command]
pub async fn ollama_health(state: State<'_, AppState>) -> Result<Health> {
    let (client, base_url) = (state.http.clone(), state.base_url());
    Ok(ollama::health(&client, &base_url).await)
}

#[tauri::command]
pub fn get_base_url(state: State<'_, AppState>) -> String {
    state.base_url()
}

#[tauri::command]
pub fn set_base_url(state: State<'_, AppState>, base_url: String) -> Result<String> {
    let trimmed = base_url.trim().trim_end_matches('/').to_string();
    if !(trimmed.starts_with("http://") || trimmed.starts_with("https://")) {
        return Err(HushError::Other(
            "base URL must start with http:// or https://".into(),
        ));
    }
    *lock(&state.base_url) = trimmed.clone();
    Ok(trimmed)
}

